for _, d in ipairs(L) do
	local page = pages[d[1]]
	if page and page[3] then
		local groups, byName = page[3], {}
		for _, g in ipairs(groups) do byName[g[1]] = g end
		-- the new dungeons' "not found yet" placeholder goes once there's real loot
		if #groups == 1 and groups[1][1] == "Bosses and loot not found yet" then table.remove(groups, 1); byName = {} end
		local firstOther                                   -- (bosses Forever added go in before "Quest rewards" and the like)
		for i, g in ipairs(groups) do if g[1] == "Quest rewards" or g[1] == "Trash" then firstOther = i; break end end
		for _, b in ipairs(d[2]) do
			local g = byName[b[1]]
			if g then g[4] = b[2]
			else
				g = { b[1], 1, 0, b[2] }
				if firstOther then table.insert(groups, firstOther, g); firstOther = firstOther + 1 else groups[#groups + 1] = g end
				byName[b[1]] = g
			end
		end
		page.foreverLoot = true
	end
end
